export type PixelObjectName = keyof typeof pixelMaps;

const ghostRows = (rows: PixelMap) => rows.map((row, y) => Array.from(row, (colour, x) => (colour === "k" && (x + y) % 2 === 0 ? "#" : ".")).join(""));

const compiled = Object.fromEntries(
  Object.entries(pixelMaps).map(([name, rows]) => [name, { solid: compilePixels(rows, pixelPalette), ghost: glyphPath(ghostRows(rows)), width: rows[0].length, height: rows.length }]),
) as Record<PixelObjectName, { solid: ReturnType<typeof compilePixels>; ghost: string; width: number; height: number }>;

function Paths({ ghost, name }: { ghost?: boolean; name: PixelObjectName }) {
  return ghost
    ? <path d={compiled[name].ghost} fill="currentColor" stroke="none" />
    : <>{compiled[name].solid.map(({ colour, d, fill }) => <path d={d} fill={fill} key={colour} stroke="none" />)}</>;
}

/** One object, at a whole multiple of its 16-pixel drawing. */
export function PixelObject({ className = "", ghost = false, name, size = 32 }: { className?: string; ghost?: boolean; name: PixelObjectName; size?: 16 | 32 | 48 | 64 }) {
  const { width, height } = compiled[name];
  return (
    <svg aria-hidden="true" className={`pixel-object ${className}`.trim()} data-ghost={ghost || undefined} data-object={name} focusable="false" height={(size * height) / width} shapeRendering="crispEdges" viewBox={`0 0 ${width} ${height}`} width={size}>
      <Paths ghost={ghost} name={name} />
    </svg>
  );
}

/** A world's character, building or prop, filling the box the world gives it. */
export function PixelSprite({ className = "", name }: { className?: string; name: PixelObjectName }) {
  const { width, height } = compiled[name];
  return (
    <svg aria-hidden="true" className={`pixel-sprite ${className}`.trim()} data-object={name} focusable="false" preserveAspectRatio="xMidYMax meet" shapeRendering="crispEdges" viewBox={`0 0 ${width} ${height}`}>
      <Paths name={name} />
    </svg>
  );
}

/** A map's size in its own pixels. */
export const pixelSize = (name: PixelObjectName) => ({ width: compiled[name].width, height: compiled[name].height });
